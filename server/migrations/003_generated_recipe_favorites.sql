-- Preserve the generated Gemini recipe and the inventory details shown with it.
CREATE TABLE IF NOT EXISTS generated_recipe_favorites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipe_snapshot JSONB NOT NULL,
  inventory_snapshot JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS generated_recipe_favorites_created_at_idx
  ON generated_recipe_favorites (created_at DESC);
