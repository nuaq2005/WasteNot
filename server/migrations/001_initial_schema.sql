-- Initial WasteNot schema for Tiger Data (PostgreSQL-compatible).
-- Apply once to the configured DATABASE_URL before starting the API.

CREATE TABLE IF NOT EXISTS food_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  quantity NUMERIC(12, 3) NOT NULL DEFAULT 1,
  unit TEXT NOT NULL DEFAULT 'item',
  expiration_date DATE,
  expiration_is_estimated BOOLEAN NOT NULL DEFAULT FALSE,
  protein_g NUMERIC(12, 3),
  carbs_g NUMERIC(12, 3),
  fiber_g NUMERIC(12, 3),
  sugar_g NUMERIC(12, 3),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT food_items_quantity_nonnegative CHECK (quantity >= 0),
  CONSTRAINT food_items_nutrients_nonnegative CHECK (
    (protein_g IS NULL OR protein_g >= 0) AND
    (carbs_g IS NULL OR carbs_g >= 0) AND
    (fiber_g IS NULL OR fiber_g >= 0) AND
    (sugar_g IS NULL OR sugar_g >= 0)
  )
);

CREATE INDEX IF NOT EXISTS food_items_expiration_date_idx
  ON food_items (expiration_date ASC NULLS LAST);

CREATE TABLE IF NOT EXISTS recipes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT,
  instructions JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS recipe_ingredients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipe_id BIGINT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  quantity NUMERIC(12, 3) NOT NULL,
  unit TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT recipe_ingredients_quantity_positive CHECK (quantity > 0)
);

CREATE INDEX IF NOT EXISTS recipe_ingredients_recipe_id_idx
  ON recipe_ingredients (recipe_id);

CREATE TABLE IF NOT EXISTS recipe_favorites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipe_id BIGINT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
  -- User identity/authentication is not implemented yet. This nullable key is
  -- a future integration point; do not use it for access control until then.
  user_id TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT recipe_favorites_recipe_user_key UNIQUE (recipe_id, user_id)
);

CREATE TABLE IF NOT EXISTS recipe_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipe_id BIGINT REFERENCES recipes(id) ON DELETE SET NULL,
  recipe_name_snapshot TEXT NOT NULL,
  servings NUMERIC(12, 3) NOT NULL DEFAULT 1,
  made_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT recipe_history_servings_positive CHECK (servings > 0)
);

CREATE INDEX IF NOT EXISTS recipe_history_made_at_idx
  ON recipe_history (made_at DESC);

CREATE TABLE IF NOT EXISTS recipe_nutrient_usage (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipe_history_id BIGINT NOT NULL REFERENCES recipe_history(id) ON DELETE CASCADE,
  nutrient_category TEXT NOT NULL,
  amount_grams NUMERIC(14, 4) NOT NULL,
  source TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT recipe_nutrient_usage_nonnegative CHECK (amount_grams >= 0),
  CONSTRAINT recipe_nutrient_usage_category_key
    UNIQUE (recipe_history_id, nutrient_category)
);

CREATE INDEX IF NOT EXISTS recipe_nutrient_usage_history_id_idx
  ON recipe_nutrient_usage (recipe_history_id);
