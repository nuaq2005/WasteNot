-- Run in the configured Snowflake database and schema before using recipe insights.
-- The application sets DATABASE and SCHEMA on its Snowflake connection.
CREATE TABLE IF NOT EXISTS RECIPE_NUTRIENT_USAGE (
  DATASET_ID VARCHAR NOT NULL,
  RECIPE_HISTORY_ID VARCHAR NOT NULL,
  EVENT_DATE DATE NOT NULL,
  NUTRIENT_CATEGORY VARCHAR NOT NULL,
  AMOUNT_GRAMS NUMBER(14, 4) NOT NULL,
  SOURCE VARCHAR NOT NULL,
  CONSTRAINT RECIPE_NUTRIENT_USAGE_AMOUNT_NONNEGATIVE CHECK (AMOUNT_GRAMS >= 0)
);
